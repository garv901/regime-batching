"""jsonl -> parquet/csv + ATTN_SWEEP.md tables."""
import json, sys
from pathlib import Path
import numpy as np, pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results/microbench"
src = OUT / (sys.argv[1] if len(sys.argv) > 1 else "attn_sweep.jsonl")

COLS = ["spec", "family", "config", "B_dec", "n_prefill", "q_total", "num_actual_tokens", "sumL", "maxL",
        "meanL", "cv", "skew", "occupancy", "time_us_median", "time_us_mean", "eager_time_us", "bw_GBps",
        "maxdiff", "notes", "time_us_std", "time_us_warm", "prefill_q", "prefill_ctx", "kv_tokens_total"]
df = pd.read_json(src, lines=True)
for c in COLS:
    if c not in df:
        df[c] = np.nan
df = df[COLS]
df.to_parquet(OUT / "attn_sweep.parquet", index=False)
df.to_csv(OUT / "attn_sweep.csv", index=False)

ok = df[df.time_us_median.notna()].copy()


def md(t, floatfmt=1):
    t = t.reset_index()
    cols = list(t.columns)
    def f(x):
        if isinstance(x, float):
            return "" if np.isnan(x) else f"{x:.{floatfmt}f}"
        return str(x)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in t.iterrows():
        lines.append("| " + " | ".join(f(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def default_cfg(r):
    return "fa3_cg" if r["num_actual_tokens"] <= 512 else "fa3_auto"


piv = ok.pivot_table(index=["family", "spec"], columns="config", values="time_us_median")
meta = ok.drop_duplicates("spec").set_index("spec")[["num_actual_tokens", "B_dec", "n_prefill", "sumL", "maxL", "skew", "occupancy", "prefill_q"]]
rows = []
for (fam, spec), r in piv.iterrows():
    m = meta.loc[spec]
    dflt = default_cfg(m)
    best = r.idxmin()
    rows.append(dict(family=fam, spec=spec, tokens=int(m.num_actual_tokens), B_dec=int(m.B_dec), n_pf=int(m.n_prefill),
                     default_cfg=dflt, default_us=r.get(dflt, np.nan), best_cfg=best, best_us=r.min(),
                     fa_best_us=r[[c for c in r.index if c.startswith("fa3")]].min(),
                     xqa_us=r.get("fi_xqa", np.nan), fi_native_us=r.get("fi_native", np.nan)))
S = pd.DataFrame(rows)
S["speedup_vs_default"] = S.default_us / S.best_us
S["xqa_speedup_vs_best"] = S.xqa_us / S.best_us
S["fa_best_vs_default"] = S.default_us / S.fa_best_us
S.to_csv(OUT / "attn_sweep_best_vs_default.csv", index=False)

out = ["# Attention config-space sweep (H100, Qwen3-8B geometry: 32q/8kv heads, d=128, bf16, page 16)\n",
       "Generated by microbench/summarize_attn_sweep.py from results/microbench/attn_sweep.{parquet,csv}. "
       "Timings are CUDA-graph replays with a 128 MB L2 flush before each call (flush cost subtracted), i.e. KV is streamed from HBM.\n",
       f"Rows: {len(df)} ({len(ok)} timed), specs: {df.spec.nunique()}.\n"]

# (a) F5
f5 = ok[ok.family == "F5_single"]
if len(f5):
    out.append("## (a) Single long sequence / single-CTA streaming bandwidth (family 5, B=1)\n")
    t = f5.pivot_table(index="spec", columns="config", values="time_us_median")
    t = t[[c for c in ["fa3_s1", "fa3_s2", "fa3_s4", "fa3_s8", "fa3_s16", "fa3_auto", "fa3_cg", "fi_xqa", "fi_native", "fi_native_nosplit", "triton"] if c in t]]
    t.index = t.index.map(lambda s: int(s.split("s")[-1]))
    t = t.sort_index(); t.index.name = "L"
    out.append("Time (us, cold L2):\n\n" + md(t) + "\n")
    bw = pd.DataFrame(index=t.index)
    per_head_bytes = bw.index.values * 128 * 2 * 2
    bw["fa3_s1: per-CTA GB/s (bytes per kv head / time)"] = per_head_bytes / (t["fa3_s1"].values * 1e-6) / 1e9
    for c in ["fa3_auto", "fa3_cg", "fi_xqa"]:
        if c in t:
            bw[f"{c}: total GB/s"] = per_head_bytes * 8 / (t[c].values * 1e-6) / 1e9
    w = f5.pivot_table(index="spec", columns="config", values="time_us_warm")
    if "fa3_s1" in w:
        w.index = w.index.map(lambda s: int(s.split("s")[-1])); w = w.sort_index()
        bw["fa3_s1 warm-L2: per-CTA GB/s"] = per_head_bytes / (w["fa3_s1"].values * 1e-6) / 1e9
    bw["fa3_s1 / fa3_auto slowdown"] = t["fa3_s1"] / t["fa3_auto"]
    bw.index.name = "L"
    out.append("Bandwidth:\n\n" + md(bw, 1) + "\n")

# (b) per family
out.append("## (b) Best config vs vLLM default, per family\n")
out.append("Default FA = fa3_cg if num_actual_tokens <= 512 else fa3_auto; FlashInfer default = fi_xqa. "
           "speedup = default_time / best_time over ALL configs (oracle); `fa_best_vs_default` restricts best to FA3 configs; "
           "`xqa/best` = fi_xqa time / best time.\n")
fam_rows = []
for fam, g in S.groupby("family"):
    wins = g.best_cfg.value_counts().head(4).to_dict()
    fam_rows.append(dict(family=fam, n_specs=len(g), geomean_speedup=np.exp(np.log(g.speedup_vs_default).mean()),
                         median_speedup=g.speedup_vs_default.median(), max_speedup=g.speedup_vs_default.max(),
                         frac_gt_1p05=(g.speedup_vs_default > 1.05).mean(),
                         geomean_fa_best_vs_default=np.exp(np.log(g.fa_best_vs_default).mean()),
                         geomean_xqa_over_best=np.exp(np.log(g.xqa_speedup_vs_best).mean()),
                         best_cfg_wins=str(wins)))
out.append(md(pd.DataFrame(fam_rows).set_index("family"), 2) + "\n")

for fam, g in S.groupby("family"):
    out.append(f"### {fam}\n")
    g = g.sort_values("speedup_vs_default", ascending=False)
    cols = ["spec", "tokens", "default_cfg", "default_us", "best_cfg", "best_us", "speedup_vs_default", "xqa_us", "xqa_speedup_vs_best"]
    show = g if len(g) <= 25 else g.head(15)
    out.append(("Top %d of %d specs by speedup:\n\n" % (len(show), len(g)) if len(g) > 25 else "") + md(show[cols].set_index("spec"), 2) + "\n")

# (c) crossovers
out.append("## (c) Crossovers\n")
f1 = ok[ok.family == "F1_homog"]
if len(f1):
    t = S[S.family == "F1_homog"].copy()
    t["B"] = t.spec.str.extract(r"^(\d+)q")[0].astype(int); t["L"] = t.spec.str.extract(r"s(\d+)$")[0].astype(int)
    g1 = t.pivot(index="B", columns="L", values="best_cfg")
    g2 = t.pivot(index="B", columns="L", values="speedup_vs_default")
    out.append("Homogeneous decode, best config per (B rows x L cols):\n\n" + md(g1) + "\n")
    out.append("Homogeneous decode, default/best speedup:\n\n" + md(g2, 2) + "\n")
    g3 = t.pivot(index="B", columns="L", values="xqa_speedup_vs_best")
    out.append("Homogeneous decode, fi_xqa/best:\n\n" + md(g3, 2) + "\n")
f3 = S[S.family == "F3_mixed"]
if len(f3):
    ph = ok[ok.config == "fa3_phase_split"].set_index("spec").time_us_median
    f3 = f3.copy(); f3["phase_split_us"] = f3.spec.map(ph)
    f3["auto_us"] = f3.spec.map(ok[ok.config == "fa3_auto"].set_index("spec").time_us_median)
    f3["cg_us"] = f3.spec.map(ok[ok.config == "fa3_cg"].set_index("spec").time_us_median)
    f3["auto/phase_split"] = f3.auto_us / f3.phase_split_us
    f3["auto/cg"] = f3.auto_us / f3.cg_us
    out.append("Mixed steps (family 3): fa3_auto (vLLM default for >512 tokens) vs fa3_cg-style forced splits vs fa3_phase_split:\n\n" +
               md(f3[["spec", "tokens", "auto_us", "cg_us", "phase_split_us", "auto/cg", "auto/phase_split", "best_cfg", "best_us"]].set_index("spec"), 2) + "\n")
out.append("Overall count of best-config wins (all specs):\n\n" + md(S.best_cfg.value_counts().to_frame("wins")) + "\n")

# (d) anomalies
out.append("## (d) Anomalies / failures\n")
err = df[df.notes.fillna("").str.contains("ERROR|failed|FLAG")]
out.append(f"Rows with errors / graph failures / maxdiff>2e-2: {len(err)}\n")
if len(err):
    out.append(md(err[["spec", "config", "maxdiff", "notes"]].head(60).set_index("spec")) + "\n")
mdm = df.groupby("config").maxdiff.max().to_frame("max maxdiff vs fa3_auto")
out.append("Max abs diff vs fa3_auto per config:\n\n" + md(mdm, 4) + "\n")
cg = df[df.config == "fa3_cg"].notes.fillna("")
out.append(f"fa3_cg metadata identical to vLLM's full-cudagraph builder output (<=512 tokens): "
           f"{cg.str.contains('md_match=True').sum()} match, {cg.str.contains('md_match=False').sum()} mismatch.\n")
(OUT / "ATTN_SWEEP_tables.md").write_text("\n".join(out))
print("wrote", OUT / "ATTN_SWEEP_tables.md")
