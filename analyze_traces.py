import pandas as pd, numpy as np, json, os
from transformers import AutoTokenizer
rows=[]; schemas={}
def pct(x): return [np.percentile(x,q) for q in (10,50,90,99)]+[x.max()]
def add(name,src,fn,inp,out,ts=None,note=""):
    inp=np.asarray(inp); out=np.asarray(out); n=len(out)
    dur=rate=np.nan
    if ts is not None and n>1:
        dur=float(ts.max()-ts.min()); rate=n/dur if dur>0 else np.nan
    r=dict(trace=name,file=fn,source=src,n_requests=n,duration_s=dur,mean_rate_rps=rate)
    for k,v in zip(["in_p10","in_p50","in_p90","in_p99","in_max"],pct(inp)): r[k]=v
    for k,v in zip(["out_p10","out_p50","out_p90","out_p99","out_max"],pct(out)): r[k]=v
    r["out_mean"]=out.mean(); r["out_cv"]=out.std()/out.mean()
    r["frac_out_le64"]=(out<=64).mean(); r["frac_out_ge1024"]=(out>=1024).mean(); r["frac_out_ge4096"]=(out>=4096).mean()
    r["frac_out_ge256"]=(out>=256).mean()
    r["note"]=note; rows.append(r); print(name,n,flush=True)
